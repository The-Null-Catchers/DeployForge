import { readFileSync } from 'node:fs';
import { z } from 'zod';

const bool = z
  .string()
  .optional()
  .transform((v) => v === 'true' || v === '1');
const int = (def: number) =>
  z
    .string()
    .optional()
    .transform((v) => (v === undefined || v === '' ? def : Number.parseInt(v, 10)))
    .pipe(z.number().int());
const list = z
  .string()
  .optional()
  .transform((v) =>
    (v ?? '')
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean),
  );

const schema = z.object({
  NODE_ENV: z.enum(['development', 'production', 'test']).default('development'),
  DEPLOYFORGE_PROCESS: z.enum(['api', 'worker', 'all']).default('all'),
  PORT: int(3000),
  HOST: z.string().default('0.0.0.0'),
  DATABASE_URL: z.string().min(1),
  REDIS_URL: z.string().min(1).default('redis://127.0.0.1:6379'),
  PUBLIC_URL: z.string().url().default('http://localhost:5173'),
  TRUST_PROXY: bool,
  COOKIE_SECURE: z.string().optional(),

  // Secrets. Generated by scripts/setup.mjs; never committed.
  SESSION_SECRET: z.string().min(32, 'SESSION_SECRET must be at least 32 characters'),
  DEPLOYFORGE_MASTER_KEYS: z.string().min(1),
  DEPLOYFORGE_ACTIVE_KEY_ID: z.string().min(1),
  SETUP_TOKEN: z.string().optional(),

  RUNNER_URL: z.string().url().default('http://127.0.0.1:7070'),
  RUNNER_SHARED_SECRET: z.string().min(32),

  // Routing
  APPS_DOMAIN: z.string().min(1).default('localhost'),
  APPS_URL_SCHEME: z.enum(['http', 'https']).default('http'),
  APPS_PUBLIC_PORT: int(0),
  TLS_MODE: z.enum(['off', 'internal', 'acme']).default('off'),
  ACME_EMAIL: z.string().optional(),
  ACME_CA: z.string().optional(),
  CADDY_ADMIN_URL: z.string().default('unix:///run/caddy-admin/admin.sock'),
  CADDY_ADMIN_LISTEN: z.string().default('unix//run/caddy-admin/admin.sock|0666'),
  CADDY_PROBE_URL: z.string().default('http://127.0.0.1:9080'),
  PROXY_PROBE_TOKEN: z.string().min(16),
  DASHBOARD_HOSTNAME: z.string().optional(),
  DASHBOARD_UPSTREAM: z.string().optional(),
  PUBLIC_IPV4: z.string().optional(),
  DNS_SERVERS: list,

  // Engine
  DEPLOY_WORKER_CONCURRENCY: int(4),
  BUILD_TIMEOUT_SECONDS: int(1200),
  DRAIN_SECONDS: int(15),
  STOP_TIMEOUT_SECONDS: int(20),
  RELEASES_TO_RETAIN: int(5),
  LOG_RETENTION_DAYS: int(14),
  MAX_BUILD_LOG_LINES: int(20000),
  MAX_BUILD_LOG_BYTES: int(5 * 1024 * 1024),
  LEASE_SECONDS: int(90),
  RECONCILE_INTERVAL_SECONDS: int(60),
  PIDS_LIMIT: int(512),
  GIT_EXTRA_ALLOWED_HOSTS: list,

  // GitHub App
  GITHUB_MODE: z.enum(['disabled', 'real', 'fixture']).default('disabled'),
  GITHUB_APP_ID: z.string().optional(),
  GITHUB_APP_SLUG: z.string().optional(),
  GITHUB_APP_PRIVATE_KEY: z.string().optional(),
  GITHUB_APP_PRIVATE_KEY_FILE: z.string().optional(),
  GITHUB_WEBHOOK_SECRET: z.string().optional(),
  GITHUB_CLIENT_ID: z.string().optional(),
  GITHUB_CLIENT_SECRET: z.string().optional(),
  MOBILE_APP_SCHEME: z.string().default('deployforge'),

  // Sessions
  SESSION_TTL_HOURS: int(24 * 7),
  SESSION_IDLE_HOURS: int(24),
  ACCESS_TOKEN_TTL_SECONDS: int(600),
  REFRESH_TOKEN_TTL_DAYS: int(30),
  API_DOCS_ENABLED: z.string().optional(),
  WEB_DIST_DIR: z.string().optional(),
});

export type AppConfig = Omit<z.infer<typeof schema>, 'COOKIE_SECURE' | 'API_DOCS_ENABLED'> & {
  cookieSecure: boolean;
  apiDocsEnabled: boolean;
  githubPrivateKey: string | null;
  isProduction: boolean;
};

export function loadConfig(env: NodeJS.ProcessEnv = process.env): AppConfig {
  const parsed = schema.safeParse(env);
  if (!parsed.success) {
    const msg = parsed.error.issues.map((i) => `  ${i.path.join('.')}: ${i.message}`).join('\n');
    throw new Error(`Invalid DeployForge configuration:\n${msg}`);
  }
  const c = parsed.data;
  const isProduction = c.NODE_ENV === 'production';
  if (c.TLS_MODE === 'acme' && !c.ACME_EMAIL) throw new Error('ACME_EMAIL is required when TLS_MODE=acme');
  if (isProduction && c.GIT_EXTRA_ALLOWED_HOSTS.length > 0 && env.DEPLOYFORGE_ALLOW_TEST_GIT_HOSTS !== 'true') {
    throw new Error('GIT_EXTRA_ALLOWED_HOSTS is a test-only setting and is refused in production');
  }
  if (isProduction && c.GITHUB_MODE === 'fixture') throw new Error('GITHUB_MODE=fixture is not allowed in production');
  let githubPrivateKey: string | null = c.GITHUB_APP_PRIVATE_KEY?.replace(/\\n/g, '\n') ?? null;
  if (!githubPrivateKey && c.GITHUB_APP_PRIVATE_KEY_FILE) githubPrivateKey = readFileSync(c.GITHUB_APP_PRIVATE_KEY_FILE, 'utf8');
  if (c.GITHUB_MODE === 'real') {
    for (const k of ['GITHUB_APP_ID', 'GITHUB_APP_SLUG', 'GITHUB_WEBHOOK_SECRET', 'GITHUB_CLIENT_ID', 'GITHUB_CLIENT_SECRET'] as const) {
      if (!c[k]) throw new Error(`${k} is required when GITHUB_MODE=real`);
    }
    if (!githubPrivateKey) throw new Error('GITHUB_APP_PRIVATE_KEY or GITHUB_APP_PRIVATE_KEY_FILE is required when GITHUB_MODE=real');
  }
  const { COOKIE_SECURE, API_DOCS_ENABLED, ...rest } = c;
  return {
    ...rest,
    cookieSecure: COOKIE_SECURE === undefined ? c.PUBLIC_URL.startsWith('https://') : COOKIE_SECURE === 'true',
    apiDocsEnabled: API_DOCS_ENABLED === undefined ? true : API_DOCS_ENABLED === 'true',
    githubPrivateKey,
    isProduction,
  };
}

export const CONFIG = Symbol('CONFIG');
